import { describe, expect, it } from 'vitest'
import type { CredentialKind } from '#/hooks/use-automation'
import { credentialSummary } from '#/pages/automation/lib/credential-summary'
import {
	credential,
	HMAC,
	SQL,
} from '#/pages/automation/test/credential-fixtures'

function summary(
	kind: string,
	data: Record<string, unknown> = {},
	overrides: Partial<ReturnType<typeof credential>> = {},
	descriptor?: CredentialKind,
) {
	return credentialSummary(credential({ kind, data, ...overrides }), descriptor)
}

describe('credentialSummary', () => {
	it('names the user of a login-based kind', () => {
		expect(summary('http_basic', { username: 'alice' })).toBe(
			'Utilisateur alice',
		)
		expect(summary('digest', { username: 'bob' })).toBe('Utilisateur bob')
	})

	it('names where a key travels', () => {
		expect(summary('bearer_token')).toBe('En-tête Authorization: Bearer')
		expect(summary('http_header', { header_name: 'X-API-Key' })).toBe(
			'En-tête X-API-Key',
		)
		expect(summary('api_key_query', { param_name: 'api_key' })).toBe(
			'Paramètre api_key',
		)
	})

	it('shows the connected account of an OAuth kind, or that none is connected', () => {
		expect(
			summary('oauth2_authorization_code', {}, { account: 'a@exemple.fr' }),
		).toBe('Connecté : a@exemple.fr')
		expect(summary('oauth1', {}, { account: null })).toBe('Compte non connecté')
	})

	it('shows the host the token comes from for client credentials', () => {
		expect(
			summary('oauth2_client_credentials', {
				token_url: 'https://auth.exemple.fr/token',
			}),
		).toBe('Jeton via auth.exemple.fr')
	})

	it('describes the signing and certificate kinds without showing anything sensitive', () => {
		expect(summary('jwt', { algorithm: 'RS256' })).toBe('Signature RS256')
		expect(summary('mtls')).toBe('Certificat et clé privée')
		expect(summary('custom_auth')).toBe('Définition JSON')
	})

	it('labels the algorithm with the option the descriptor offers', () => {
		expect(
			summary(
				'hmac',
				{ header_name: 'X-Signature', algorithm: 'sha256' },
				{},
				HMAC,
			),
		).toBe('En-tête X-Signature · SHA-256')
	})

	it('shows the address of a server, a database or a mail host', () => {
		expect(
			summary('ssh', { username: 'deploy', host: 'srv.exemple.fr', port: 22 }),
		).toBe('deploy@srv.exemple.fr:22')
		expect(
			summary(
				'sql',
				{
					engine: 'postgres',
					host: 'db.exemple.fr',
					port: 5432,
					database: 'app',
				},
				{},
				SQL,
			),
		).toBe('PostgreSQL · db.exemple.fr:5432/app')
		expect(summary('smtp', { host: 'smtp.exemple.fr', port: 465 })).toBe(
			'smtp.exemple.fr:465',
		)
	})

	it('shows the instance of an Odoo key', () => {
		expect(
			summary('odoo_api', {
				base_url: 'https://mon-entreprise.odoo.com',
				database: 'prod',
			}),
		).toBe('mon-entreprise.odoo.com · prod')
	})

	it('says a secret generated by Mestier is so, whatever the kind', () => {
		expect(summary('bearer_token', {}, { origin: 'generated' })).toBe(
			'Générée par Mestier',
		)
	})

	it('falls back to "Fournie" for a kind without anything to show', () => {
		expect(summary('mystery')).toBe('Fournie')
	})
})
