use axum::{
    extract::{State, rejection::PathRejection},
    response::{IntoResponse, Response as HttpResponse},
};
use handlers::{ApiError, AppState, DataEnvelope, Response};

use crate::response::public::{PublicSurveyResponsesPath, StartedPublicResponseView, hidden, slug};

#[utoipa::path(
    post,
    path = "/api/v1/public/surveys/{slug}/responses",
    operation_id = "startPublicSurveyResponse",
    tag = super::super::super::TAG,
    description = "Starts a response to an opened public survey, without an account. The response carries its resume token, generated by the server, here and only here: keep it to resume, save, upload photos and complete. Rate limited per client address (60 starts a minute) and per survey (600 starts a minute).",
    params(
        ("slug" = String, Path, description = "The public slug of the survey"),
    ),
    responses(
        (status = 201, description = "Response started, with its resume token", body = inline(DataEnvelope<StartedPublicResponseView>)),
        (status = 404, description = "No opened public survey behind this link"),
        (status = 409, description = "Closed or outside its campaign window (details.reason)"),
        (status = 429, description = "Too many requests"),
    ),
)]
pub async fn handler(
    path: Result<PublicSurveyResponsesPath, PathRejection>,
    State(state): State<AppState>,
) -> Result<HttpResponse, ApiError> {
    let PublicSurveyResponsesPath { slug: value } = path.map_err(|_| ApiError::NotFound)?;
    let slug = slug(value)?;

    let response = state
        .usecase
        .start_public_response(&slug)
        .await
        .map_err(hidden)?;

    Ok(Response::Created(StartedPublicResponseView::of(&response)?).into_response())
}
